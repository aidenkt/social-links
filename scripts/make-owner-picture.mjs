// Builds the 512x512 WebP that aiden.social reports to KT Accounts as Aiden's picture on
// this site (PUT /oauth/identity/picture). KT accepts only a plain 512x512 WebP or JPEG
// with no metadata, so the bytes are written once here and embedded in a server module.
// Run: node scripts/make-owner-picture.mjs
import sharp from 'sharp'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, 'public', 'favicon.png')
const buf = await sharp(src)
  .resize(512, 512, { fit: 'cover', kernel: 'lanczos3' })
  .removeAlpha()
  .webp({ quality: 90 })
  .toBuffer()
const out = path.join(root, 'src', 'lib', 'auth', 'owner-picture.ts')
writeFileSync(
  out,
  `// Generated by scripts/make-owner-picture.mjs from public/favicon.png. Do not edit.\n` +
    `// 512x512 WebP, ${buf.length} bytes: the picture aiden.social reports to KT Accounts.\n` +
    `export const OWNER_PICTURE_WEBP_BASE64 =\n  '${buf.toString('base64')}'\n`
)
console.log(`wrote ${out} (${buf.length} bytes)`)
